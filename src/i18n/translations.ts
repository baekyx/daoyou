function preserveOuterWhitespace(source: string, translated: string): string {
  const leading = source.match(/^\s*/)?.[0] ?? '';
  const trailing = source.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

export function translateUiText(source: string, locale: AppLocale): string {
  if (locale === 'zh-CN' || !/[\u4e00-\u9fff]/.test(source)) return source;
  const trimmed = source.trim();
  const exact = EN_UI_COPY[trimmed];
  if (exact) return preserveOuterWhitespace(source, exact);
  for (const [pattern, create] of UI_PATTERNS) {
    const match = trimmed.match(pattern);
    if (match) return preserveOuterWhitespace(source, create(...match.slice(1)));
  }
  return source;
}
